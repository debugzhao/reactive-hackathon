const DICT: Record<Lang, Record<Key, string>> = { en, zh };
const STORAGE_KEY = "qvs.lang";

export type T = (key: Key, vars?: Record<string, string | number | bigint>) => string;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number | bigint>): string {
  const s = DICT[lang][key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

const isLang = (x: unknown): x is Lang => x === "en" || x === "zh";

function detect(): Lang {
  const q = new URLSearchParams(location.search).get("lang");
  if (isLang(q)) return q;
  const saved = localStorage.getItem(STORAGE_KEY);
  if (isLang(saved)) return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: T };
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detect);

  // 同步 <html lang>、标题、格式化 locale，并把语言写进 URL（保留 #锚点）
  setFormatLocale(lang);
  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.title = translate(lang, "doc.title");
    const u = new URL(location.href);
    if (u.searchParams.get("lang") !== lang) {
      u.searchParams.set("lang", lang);
      history.replaceState(history.state, "", u);
    }
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    localStorage.setItem(STORAGE_KEY, l);
    setLangState(l);
  }, []);
  const t = useCallback<T>((key, vars) => translate(lang, key, vars), [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n must be used inside <I18nProvider>");
  return c;
}
